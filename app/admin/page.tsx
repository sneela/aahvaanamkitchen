import { redirect } from 'next/navigation';
import { authConfigured, requireAdmin } from '@/lib/auth/session';
import { mongoConfigured } from '@/lib/mongodb/client';
import AdminDashboard from './dashboard';

export const dynamic = 'force-dynamic';

export default async function AdminPage() {
  const databaseReady = mongoConfigured();
  const credentialsReady = authConfigured();

  if (!databaseReady || !credentialsReady) {
    return (
      <main className="admin-shell">
        <div className="admin-body" style={{ maxWidth: 780 }}>
          <h1>Administrator setup required</h1>
          <p>Before signing in, configure the Aahvaanam Kitchen server environment in Netlify. The website can still display its sample menu, but online ordering remains disabled until the database is ready and you enable it.</p>
          <section className="admin-card" aria-label="Setup checklist">
            <h2>Configuration checklist</h2>
            <p>MongoDB connection: <strong>{databaseReady ? 'Configured' : 'Not configured'}</strong></p>
            <p>Administrator authentication: <strong>{credentialsReady ? 'Configured' : 'Not configured'}</strong></p>
            <p>In Netlify, open <strong>Project configuration → Environment variables</strong> and set these server-side values:</p>
            <ul>
              <li><code>MONGODB_URI</code> — private Atlas connection string</li>
              <li><code>MONGODB_DB_NAME</code> — <code>aahvaanam_kitchen</code></li>
              <li><code>ADMIN_EMAIL</code> — administrator sign-in email</li>
              <li><code>ADMIN_PASSWORD_HASH</code> — generated with <code>npm run admin:hash</code></li>
              <li><code>SESSION_SECRET</code> — random secret generated by the same command</li>
            </ul>
            <p>Redeploy after saving variables. Initialize Atlas privately with <code>npm run mongo:indexes</code>, <code>npm run mongo:seed</code>, and <code>npm run mongo:verify</code> using the same environment values.</p>
            <p><strong>Never paste your connection string or passwords into a chat or commit them to GitHub.</strong></p>
            <a href="https://app.netlify.com/" target="_blank" rel="noopener noreferrer">Open Netlify dashboard</a>
          </section>
          <p><a href="/">Return to website</a></p>
        </div>
      </main>
    );
  }

  try { await requireAdmin(); } catch { redirect('/admin/login'); }
  return <AdminDashboard />;
}
